/** The same troubles, said by anyone at the door. */
function common(o: Outcome): string | null {
  if (o.arrests) return 'Говорят, тебя милиция останавливала? Ну, бывает. Главное — доехал. Давай, что привёз.';
  if (o.damage > 0.5) return 'Ох, а машина-то как побита… Ты сам цел? Ну, давай почту, а то ещё развалится по дороге.';
  if (o.cargo < 60) return 'Ой, что-то звенит… Побил, да? Ну, не со зла. Дорога у нас — сам видишь какая.';
  if (o.left < -60) return 'Ждали тебя, ждали… Ну ничего, доехал — и ладно. Давай сюда.';
  if (o.stuck > 1) return 'Сапоги-то в грязи по колено. Садился, да? У нас все садятся. Давай почту, отмоешься.';
  if (o.rain > 0.5) return 'Под таким дождём приехал? Ну ты даёшь. Давай почту, а сам обсохни хоть минутку.';
  if (o.dark > 0.5) return 'Темно уже, а ты всё ездишь. Спасибо. Езжай аккуратнее, на дороге ни души.';
  return null;
}

const pick = <T>(l: T[]): T => l[Math.floor(Math.random() * l.length)];

/**
 * A short scene at the door. Each woman has a line for every kind of trip — the worse
 * the trip, the more she has to say about it — and a plain one when all went well.
 */
export function storyFor(id: string, o: Outcome, plain: string): string {
  const v = (road: string) => o.visited.includes(road);
  const kinds = o.kinds ?? [];
  // the original lines are about a pension (Sosnovka) and jars for the shop (Zarechye); other cargo gets its own
  const classic = (id === 'sosnovka' && kinds.includes('pension')) || (id === 'zarechye' && kinds.includes('parcel'));
  if (!classic) {
    const c = common(o);
    if (c) return c;
    if (id === 'kainly' && v('quarry')) return 'Ты что, в карьер заезжал? Там раньше весь район песок брал, а теперь только мальчишки на великах. Ну, давай почту, улым.';
    const about = kinds.map((k) => ABOUT[id]?.[k]).find(Boolean);
    if (REMEMBER[id] && Math.random() < 0.2) return pick(REMEMBER[id]);
    return about ? pick(about) : plain;
  }
  if (id === 'sosnovka') {
    if (o.arrests) return 'Сынок, мне из района звонили — тебя милиция вязала? Господи… Ты уж там не безобразничай, пенсию принёс — и спасибо. Яблок возьми, не побрезгуй.';
    if (o.damage > 0.5) return 'Батюшки, да что с машиной-то?! Мотор парит, лобовое в трещинах… Лихо ты. Пенсию-то привёз, главное — а машину тебе, милый, в мастерскую надо.';
    if (o.stuck > 1) return 'Грязь-то по самую крышу, вижу. Сколько раз садился? Дорога у нас — одно название. Заходи, чай поставила, вытрешь сапоги вон о тряпку.';
    if (v('village-lane')) return 'Ой, ты задворками приехал, огородами? Это Степаныч тебя научил? Хитрый… Ну проходи, газеты давай. Яблок свежих положила, антоновка.';
    if (o.cargo < 70) return 'Газеты-то мятые какие, и банка твоя звякает… Ничего, я не жалуюсь, пенсия дороже. А ты, сынок, на ямах потише — не железный ведь.';
    if (o.rain > 0.3) return 'Промок поди, под дождём-то? Заходи, обогрейся, пенсию давай. Яблок вот возьми, из погреба. В такую погоду добрый хозяин собаку не выгонит.';
    if (o.left > 360) return 'Ой, быстро как! Я и чайник не поставила. Ты что, летел? Ну, хорошо, пенсию вовремя привёз, а то Клавдия ждёт, ей за свет платить.';
    return plain;
  }
  // Zarechye
  if (o.arrests) return 'Милиция тебя забирала? Мне Нинка из Сосновки по телефону сказала… Ну что ж. Посылки целы — и ладно. Накладные давай, а об остальном не мне судить.';
  if (o.cargo < 55) return 'Господи, что в кузове было — землетрясение? Банки вдребезги, всё склеилось. Акт составлю, а ты, милок, подпиши, что видел сам.';
  if (o.damage > 0.5 && o.left < 0) return 'Явился наконец, весь в мыле, машина еле дышит, я уж на обед ушла и вернулась… Ладно, не ругаюсь. Накладные, посылки — всё сюда.';
  if (o.damage > 0.5) return 'Ты, что, в столб въехал? Капот-то парит! Заходи, воды вынесу, пока не закипел совсем. А посылки давай, я приму.';
  if (o.left < 0 && o.cargo < 80) return 'Явился! Я уж закрыла, на обед ушла… А посылки-то мокрые — банки побил? Ой, горе. Накладные давай, акт составлять будем.';
  if (o.cargo < 80) return 'Через Серебрянку перебрался — и то ладно. А что посылки звенят? Банки побились, что ли… Ну, накладные давай, акт составим.';
  if (o.left < 0) return 'Наконец-то! Я уж на обед закрывать собралась, полчаса тут стою. Ладно, заноси посылки, накладные — мне.';
  if (o.stuck > 1) return 'Опять в низине сел? Все там садятся, колхозный трактор вытаскивать устаёт. Ничего, главное — доехал. Посылки неси, чаю налью.';
  if (v('khutor-loop') || v('forestry-ring')) return pick([
    'Ты что, объездными ехал, мимо хутора? Любопытный. Там у Берёзок нынче дорога сухая, а через лес — заросла. Ну, посылки неси.',
    'Мне Колька с хутора говорил: видел почтовую машину, ехала по гравийке. Ты, видать, дорогу знаешь лучше начальства. Заноси.',
  ]);
  if (o.rain > 0.3 && o.left > 120) return 'Ливень-то какой, а ты как по маслу доехал! Переждать не хочешь? Чай будешь? Посылки ставь вон на прилавок.';
  if (o.dark > 0.5) return 'Темнеет уже, а ты ещё в дороге… Поставь посылки, чаю выпей, да спеши домой — на дороге ни души.';
  if (o.left > 300 && o.cargo > 92) return 'Как по часам и всё целое! Начальник будет доволен. Вот бы все так ездили — вечно жди этих посылок. Чай будешь?';
  return plain;
}
