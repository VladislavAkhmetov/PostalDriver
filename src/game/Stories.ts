/** How the run went when the parcels were handed over; the addressee's words depend on it. */
export interface Outcome {
  /** Parcels' condition, 0…100. */
  cargo: number;
  /** Seconds of schedule left (negative when late). */
  left: number;
  /** Crash damage of the van, 0…1. */
  damage: number;
  fines: number; arrests: number; escapes: number;
  rain: number; dark: number;
  stuck: number;
  /** Ids of the back roads driven (`forest-bypass`, `khutor-loop`…). */
  visited: string[];
  /** What was brought to this door today (`pension`, `parcel`…). */
  kinds?: string[];
}

