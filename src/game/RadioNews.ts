/** The presenter's next words for today, or null to go straight to the next song. */
export class RadioNews {
  private items: string[] = [];
  private i = 0;

  constructor(profile: Profile) {
    const day = profile.day;
    const r = mulberry32(day * 613 + 17);
    const tomorrow = boardFor(day + 1, profile.trust);
    // «на среду, 5 ноября»: the weekday in the accusative
    const date = calendar(day + 1).text.toLowerCase().replace(/^(сред|пятниц|суббот)а/, '$1у');
    const weather = `Прогноз погоды на ${date}: ${tomorrow.forecast.replace(/^По радио:\s*/, '').replace(/\.$/, '')}. Водителям на грунтовках — передний мост и терпение.`;
    const story: string[] = [];
    const m = profile.muha;
    // the district's news while it is news: the sawmill until chapter three, the cigarettes until the sawmill
    if (m?.saw && (m.step === 'after2' || m.step === 'wait' || m.step === 'pressed')) story.push('Новости района: на пилораме у Заречья сменился хозяин. Говорят, теперь пиловочник принимают по новым ценам. Какие цены — не говорят.');
    if (m?.outcome === 'seized' && !m.saw) story.push('ГАИ Ключевского района сообщает: на посту изъята партия сигарет без акцизных марок. Сержант Кузьмин просит граждан внимательнее относиться к посылкам незнакомых людей.');
    if (m?.ending === 'quit' && !(dateParts(day).m >= 2 && dateParts(day).m < 8)) story.push('Отделение связи сообщает: с весны требуется грузчик. Говорят, место уже обещано одному молодому человеку. Без машины, зато с руками.');
    const rs = profile.roadStop;
    const fresh = rs?.day !== undefined && day - rs.day <= 3;
    if (fresh && rs?.outcome === 'robbed') story.push('Участились кражи автомагнитол. ГАИ советует снимать магнитолу на ночь. И, как выяснилось, днём тоже.');
    if (fresh && rs?.outcome === 'fled') story.push('Жители Сосновки жалуются: по большаку гоняют с музыкой — то «пятёрка» за почтовой машиной, то почтовая от «пятёрки». Просьба соблюдать скоростной режим.');
    if ((profile.letters?.done.length ?? 0) > 0) story.push('Хорошие новости от почты: письма «до востребования», пролежавшие в шкафу с девяностого года, находят адресатов. Если вы кого-то ждали — подождите ещё. Может, и вам.');
    const pick = <T>(l: T[]) => l.splice(Math.floor(r() * l.length), 1)[0];
    const { m: mon, d: dd } = dateParts(day);
    const season = seasonOf(mon, dd);
    if (m?.ending === 'quit' && m.step === 'end' && (season === 'first-snow' || season === 'winter')) story.push('Котельная Ключевска сообщает: батареи потеплели. Новый кочегар, Евгений Мухин, уголь кидает так, будто за ним гонятся. Весной, говорят, уходит на почту.');
    const notices = season === 'winter' || season === 'first-snow' ? [...WINTER_NOTICES] : mon >= 2 && mon <= 4 ? [...NOTICES, ...SPRING_NOTICES] : [...NOTICES];
    const greetings = [...GREETINGS, ...DATED.filter(([mm, a, b]) => mm === mon && dd >= a && dd <= b).map((g) => g[3])];
    // the district's own news through the season: the cases (Cases.ts) and the calendar
    const cs = profile.cases ?? {};
    if (day >= GRANDPA_HOME && day < GRANDPA_HOME + 3) story.push('Из Уфы вернулся Урал Хисамович — тридцать лет районный почтальон. Говорят, врачи велели отдыхать. Говорят, он уже три раза ходил на почту — проверить. Здоровья вам, Урал-агай!');
    if (cs.birth && day > 8 && day < 13) greetings.push('Поздравляем Рината и Зульфию из Урманлы с сыном! Три восемьсот, кричит громко — будет трактористом. Или почтальоном.');
    if (cs.wedding && day < 15) greetings.push('Поздравляем молодых из Кайынлы — Ильдара и Гузель! Совет да любовь. Дружка просил передать: почта, приходи, пирог ещё остался.');
    if (day >= 20 && day < 24) story.push('Наш земляк из Урманлы, Дмитрий Егорович, получил письмо из передачи «Поле чудес». Сам Дмитрий Егорович просил передать: «Вы ещё обо мне услышите».');
    if (mon === 1 && dd >= 19 && dd <= 23) greetings.push('Поздравляем всех мужчин района с Двадцать третьим февраля! Отдельно — механизаторов колхоза «Заря»: ребята, тракторы к весне — как новенькие.');
    if (mon === 2 && dd <= 8) greetings.push('Дорогие женщины Ключевского района! С Восьмым марта! Мимоза в райцентре кончилась к девяти утра — значит, вас любят.');
    if (mon === 5 && dd >= 8 && dd <= 14) story.push((dateParts(day).wd === 5 ? 'Сегодня' : 'В субботу') + ' в Сосновке — Сабантуй! Скачки, борьба на поясах, бег в мешках, столб с призами. Главный приз — баран. Прошлогодний чемпион по столбу просил не беспокоиться: в этом году он «в форме».');
    if (mon === 11 && dd >= 22) story.push('До Нового года — считанные дни! Радио «Заречье» поздравляет всех слушателей. В клубе Ключевска — ёлка, Дед Мороз — завклубом Пётр Ильич, Снегурочка — его дочь. Подарки — по списку.');
    if (mon === 0 && dd <= 10) story.push('С Новым, тысяча девятьсот девяносто восьмым годом! Пусть он будет лучше прошлого. Хотя куда уж лучше — сказала Зинаида Павловна и ушла разбирать открытки.');
    this.items = [weather];
    if (story.length) this.items.push(pick(story));
    this.items.push(pick(notices), pick(greetings), pick(notices));
    if (story.length) this.items.push(pick(story));
    this.items.push(pick(notices), pick(greetings));
  }

  /** Everything the presenter has for today (for the voices to decode ahead). */
  get all(): string[] { return [...this.items]; }

  next(): string | null {
    if (!this.items.length) return null;
    return this.items[this.i++ % this.items.length];
  }
}
